"""Render README.md: themed <picture> blocks around generated SVGs plus live Markdown."""

from __future__ import annotations

from datetime import date
from html import escape
from pathlib import Path

from .sections.nav import slug

BANNER = ("<!-- Generated by `python -m generator` and refreshed daily by .github/workflows/profile.yml.\n"
          "     Edit generator/content.toml (and generator/sections/) instead of this file. -->")


def picture(base: str, stem: str, alt: str, width: str | None = "100%", height: int | None = None) -> str:
    size = f' width="{width}"' if width else ""
    size += f' height="{height}"' if height else ""
    return (
        "<picture>"
        f'<source media="(prefers-color-scheme: dark)" srcset="{base}/{stem}-dark.svg">'
        f'<source media="(prefers-color-scheme: light)" srcset="{base}/{stem}-light.svg">'
        f'<img src="{base}/{stem}-dark.svg" alt="{escape(alt)}"{size}>'
        "</picture>"
    )


def block(inner: str, href: str | None = None) -> str:
    if href:
        inner = f'<a href="{href}">{inner}</a>'
    return f'<p align="center">\n  {inner}\n</p>'


def clip(text: str, limit: int = 118) -> str:
    """Trim to one line at a word boundary."""
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",.;:") + "…"


def notes_md(s: dict) -> str:
    lines = []
    for n in s["notes"]:
        title = n["title"].replace("[", "\\[").replace("]", "\\]")
        when = date.fromisoformat(n["date"])
        lines.append(f"- **[{title}]({n['link']})**<br><sub>{when:%d %b %Y} · {escape(clip(n['summary']))}</sub>")
    if s["notes_total"]:
        lines += ["", f"<sub>→ [All {s['notes_total']} field notes on geekindata.com](https://www.geekindata.com)"
                      " · this list refreshes daily from the RSS feed</sub>"]
    return "\n".join(lines)


def render(content: dict, s: dict) -> str:
    p = content["profile"]
    base = p["raw_base"]
    links = {link["label"]: link["url"] for link in content["links"]}
    head = {key: (title, table) for key, title, table in content["sections"]}

    def header(key: str) -> str:
        title, _ = head[key]
        return block(picture(base, f"h-{key}", f"{title}"))

    langs = ", ".join(f"{n} {pct:.0%}" for n, pct, _ in s["languages"][:5])
    pills = "\n  ".join(
        f'<a href="{link["url"]}">{picture(base, "link-" + slug(link["label"]), link["label"], None, 32)}</a>'
        for link in content["links"]
    )
    out = [
        BANNER,
        "",
        block(picture(base, "hero", f"{p['name_first']} {p['name_last']}: {p['role']}, Oslo. The aurora is drawn "
                                    f"from {s['total']:,} GitHub contributions over the last 365 days."),
              links["Portfolio"]),
        "",
        f'<p align="center">\n  {pills}\n</p>',
        "",
        f'<p align="center">\n  {p["intro"].strip()}\n</p>',
        "",
        header("whoami"),
        "",
        block(picture(base, "whoami", "Notebook cell running SELECT * FROM gold.people WHERE handle = 'geekindata'. Result: "
                      + "; ".join(f"{k}: {v}" for k, v in content["whoami"]["rows"]))),
        "",
        header("telemetry"),
        "",
        block(picture(base, "telemetry",
                      f"Last 365 days: {s['total']:,} contributions on {s['active']} active days, longest streak "
                      f"{s['longest_streak']} days, {s['commits']:,} commits, {s['pull_requests']:,} pull requests. "
                      f"Languages: {langs}.")),
        "",
        header("stack"),
        "",
        block(picture(base, "stack", "Periodic table of my stack: " + ", ".join(
            e["name"] for e in content["stack"]["elements"]))),
        "",
        header("work"),
        "",
        block(picture(base, "work", "Selected work: " + "; ".join(
            f"{w['client']}: {w['title']}" for w in content["work"])), links["Portfolio"] + "/#projects"),
        "",
        header("stage"),
        "",
        block(picture(base, "stage", "Talks: " + "; ".join(
            f"{x['title']} ({x['event']}, {x['when']})" for x in content["stage"]["talks"])), links["Sessionize"]),
        "",
        header("notes"),
        "",
        "<!-- field-notes:start -->",
        notes_md(s),
        "<!-- field-notes:end -->",
        "",
        header("lineage"),
        "",
        block(picture(base, "lineage", "Career: " + "; ".join(
            f"{r['title']}, {r['org']} ({r['when']})" for r in content["lineage"]))),
        "",
        header("credentials"),
        "",
        block(picture(base, "credentials", "Certifications: " + "; ".join(
            f"{c['issuer']} {c['name']} ({c['year']})" for c in content["certs"])),
              links["Portfolio"] + "/#certifications"),
        "",
        block(picture(base, "footer", "Takk for besøket (thanks for visiting)")),
        "",
    ]
    return "\n".join(out)


def update(path: Path, content: dict, s: dict) -> None:
    path.write_text(render(content, s))
