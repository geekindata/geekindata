from __future__ import annotations

from urllib.parse import quote, urlsplit

ASSET_BASE = "https://raw.githubusercontent.com/geekindata/geekindata/main/assets"
SECTIONS = (
    ("hero", "Animated Oslofjord aurora built from 365 days of GitHub contributions"),
    ("whoami", "Who I am, rendered as a SQL notebook cell"),
    ("telemetry", "Daily GitHub contributions, active days, streak, commits, pull requests, languages, and weekly rhythm"),
    ("stack", "Periodic table of data, analytics, AI, and engineering technologies"),
    ("projects", "Selected data platform and AI projects"),
    ("talks", "Conference talks and speaker profile"),
    ("career", "Career timeline as a git log graph"),
    ("certifications", "Professional certifications"),
)


def build_readme(snapshot: dict) -> str:
    blocks = []
    for name, alt in SECTIONS:
        blocks.append(
            "<picture>\n"
            f'  <source media="(prefers-color-scheme: dark)" srcset="{ASSET_BASE}/{name}-dark.svg" />\n'
            f'  <source media="(prefers-color-scheme: light)" srcset="{ASSET_BASE}/{name}-light.svg" />\n'
            f'  <img src="{ASSET_BASE}/{name}-dark.svg" alt="{alt}" width="100%" />\n'
            "</picture>"
        )
    field_notes = "\n".join(
        f"- [{_markdown_text(item['title'])}](<{_markdown_url(item['url'])}>)"
        for item in snapshot.get("feed", [])
        if item.get("title") and _is_http_url(item.get("url", ""))
    )
    if not field_notes:
        field_notes = "_New notes will appear here when the feed is available._"

    content = [
        "# Sai Prudhvi Neelakantam",
        "<!-- Generated by python -m generator. Edit generator/content.toml instead. -->",
        *blocks,
        "## Field notes",
        field_notes,
        "---",
        '<p align="center">\n  <a href="https://sai.geekindata.com">Portfolio</a> ·\n'
        '  <a href="https://linkedin.com/in/saiprudhvineelakantam">LinkedIn</a> ·\n'
        '  <a href="https://sessionize.com/saiprudhvineelakantam/">Sessionize</a> ·\n'
        '  <a href="mailto:sai@geekindata.com">Email</a>\n</p>',
    ]
    return "\n\n".join(content) + "\n"


def _markdown_text(value: str) -> str:
    return (
        value.replace("—", "-").replace("–", "-").replace("−", "-")
        .replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")
        .replace("<", "&lt;").replace(">", "&gt;")
    )


def _is_http_url(value: str) -> bool:
    parsed = urlsplit(value)
    return parsed.scheme in ("http", "https") and bool(parsed.hostname) and not parsed.username and not parsed.password


def _markdown_url(value: str) -> str:
    return quote(value, safe=":/?#@!$&'*+,;=%-._~")
